package game.models;

/**
 * Класс, представляющий крейсер в игре "Морской бой".
 * Крейсер является трехпалубным кораблем, занимающим 3 клетки на игровом поле.
 *
 * Наследуется от абстрактного класса Ship и наследует его базовую функциональность.
 * Крейсеры обычно составляют основную часть военно-морского флота в игре.
 */
public class Cruiser extends Ship {

    /**
     * Создает новый экземпляр крейсера.
     * Устанавливает название корабля "Cruiser" и размер 3 клетки.
     *
     * Конструктор не принимает параметров, так как характеристики крейсера
     * фиксированы и не могут быть изменены в рамках данной реализации игры.
     * Крейсер всегда занимает три смежные клетки на игровом поле.
     */
    public Cruiser() {
        super("Cruiser", 3);
    }
}