package game.models;

/**
 * Перечисление, определяющее возможные состояния клетки игрового поля.
 * Состояние клетки определяет ее текущий статус и влияет на отображение и взаимодействие.
 * <p>
 * Используется для отслеживания того, что находится в клетке и как она была затронута в ходе игры.
 */
public enum CellState {
    /**
     * Клетка пуста и не содержит никаких объектов.
     * Это начальное состояние всех клеток перед размещением кораблей.
     */
    EMPTY,

    /**
     * Клетка содержит часть обычного корабля (не подлодку).
     * Состояние устанавливается при размещении стандартных кораблей.
     */
    SHIP,

    /**
     * Клетка содержит подводную лодку.
     * Подлодки являются особым типом кораблей с уникальными свойствами.
     */
    SUBMARINE,

    /**
     * Клетка содержит мину.
     * Мины наносят урон и раскрывают координаты кораблей при срабатывании.
     */
    MINE,

    /**
     * Клетка содержит минный тральщик.
     * Тральщики могут раскрывать мины противника и имеют защитные свойства.
     */
    MINESWEEPER,

    /**
     * Клетка была поражена атакой (попадание).
     * Устанавливается при успешной атаке по кораблю, мине или тральщику.
     */
    HIT,

    /**
     * Атака по клетке была промахом.
     * Устанавливается при атаке по пустой клетке или уже пораженной цели.
     */
    MISS,

    /**
     * Корабль в клетке полностью уничтожен.
     * Устанавливается, когда все клетки корабля были поражены.
     */
    DESTROYED,

    /**
     * Клетка была обнаружена/раскрыта миной.
     * Используется когда мина раскрывает координаты корабля противника.
     */
    REVEALED,
}