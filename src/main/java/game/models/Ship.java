package game.models;

import java.util.ArrayList;
import java.util.List;

/**
 * Абстрактный класс, представляющий корабль в игре "Морской бой".
 * Определяет общую структуру и поведение для всех типов кораблей.
 *
 * Корабли могут быть различных типов и размеров, но все они имеют
 * общие характеристики: название, размер, здоровье и список клеток,
 * которые они занимают на игровом поле.
 */
public abstract class Ship {
    /**
     * Название корабля (например, "Battleship", "Cruiser").
     */
    protected String name;

    /**
     * Размер корабля в клетках (количество палуб).
     */
    protected int size;

    /**
     * Текущее здоровье корабля (количество неповрежденных клеток).
     */
    protected int health;

    /**
     * Список клеток, которые занимает корабль на игровом поле.
     */
    protected List<Cell> cells;

    /**
     * Флаг, указывающий потоплен ли корабль.
     */
    protected boolean isSunk;

    /**
     * Создает новый корабль с указанными характеристиками.
     * Инициализирует корабль с полным здоровьем и пустым списком клеток.
     *
     * @param name название корабля
     * @param size размер корабля в клетках
     */
    public Ship(String name, int size) {
        this.name = name;
        this.size = size;
        this.health = size;
        this.cells = new ArrayList<>();
        this.isSunk = false;
    }

    /**
     * Наносит урон кораблю при попадании.
     * Уменьшает здоровье корабля на 1 и проверяет, потоплен ли корабль.
     * Если здоровье достигает 0, помечает корабль как потопленный.
     *
     * @return true если корабль потоплен в результате этого попадания,
     *         false если корабль поврежден, но еще не потоплен
     */
    public boolean hit() {
        health--;
        if (health <= 0) {
            isSunk = true;
            markCellsDestroyed();
        }
        return isSunk;
    }

    /**
     * Помечает все клетки корабля как уничтоженные.
     * Вызывается автоматически при потоплении корабля.
     * Клетки уже помечаются при вызове hit() в методе Cell.attack(),
     * поэтому этот метод может быть оставлен пустым или использоваться
     * для дополнительной логики при потоплении.
     */
    private void markCellsDestroyed() {
        // Метод оставлен для возможного расширения функциональности
        // В текущей реализации клетки уже помечаются как DESTROYED
        // при вызове Cell.updateIfShipSunk() из Board.attack()
    }

    /**
     * Добавляет клетку к списку клеток, занимаемых кораблем.
     * Каждый корабль состоит из одной или нескольких клеток,
     * которые должны быть смежными на игровом поле.
     *
     * @param cell клетка, занимаемая кораблем
     */
    public void addCell(Cell cell) {
        cells.add(cell);
    }

    /**
     * Возвращает название корабля.
     *
     * @return название корабля
     */
    public String getName() {
        return name;
    }

    /**
     * Возвращает размер корабля в клетках.
     *
     * @return размер корабля
     */
    public int getSize() {
        return size;
    }

    /**
     * Возвращает текущее здоровье корабля.
     * Здоровье равно количеству неповрежденных клеток корабля.
     *
     * @return текущее здоровье корабля
     */
    public int getHealth() {
        return health;
    }

    /**
     * Проверяет, потоплен ли корабль.
     * Корабль считается потопленным, когда все его клетки поражены.
     *
     * @return true если корабль потоплен, false в противном случае
     */
    public boolean isSunk() {
        return isSunk;
    }

    /**
     * Возвращает список клеток, занимаемых кораблем.
     *
     * @return список клеток корабля
     */
    public List<Cell> getCells() {
        return cells;
    }
}