package game.models;

/**
 * Класс для хранения информации о выданных целях при попадании в мину или тральщик.
 * Хранит координаты цели, ее тип и статус использования.
 *
 * Используется для отслеживания информации, которая была раскрыта игрокам
 * в результате специальных событий в игре (попадание в мину, поражение тральщика).
 */
public class RevealedTarget {
    /**
     * Номер строки раскрытой цели на игровом поле.
     */
    private int row;

    /**
     * Номер столбца раскрытой цели на игровом поле.
     */
    private int col;

    /**
     * Тип раскрытой цели (корабль или мина).
     */
    private TargetType type;

    /**
     * Флаг, указывающий использована ли уже эта раскрытая информация.
     */
    private boolean used;

    /**
     * Создает новую выданную цель с указанными параметрами.
     * Инициализирует цель как неиспользованную.
     *
     * @param row строка цели на игровом поле (0-based индексация)
     * @param col столбец цели на игровом поле (0-based индексация)
     * @param type тип цели (корабль или мина)
     */
    public RevealedTarget(int row, int col, TargetType type) {
        this.row = row;
        this.col = col;
        this.type = type;
        this.used = false;
    }

    /**
     * Возвращает номер строки раскрытой цели.
     *
     * @return номер строки (0-based)
     */
    public int getRow() {
        return row;
    }

    /**
     * Возвращает номер столбца раскрытой цели.
     *
     * @return номер столбца (0-based)
     */
    public int getCol() {
        return col;
    }

    /**
     * Возвращает тип раскрытой цели.
     * Тип определяет, что именно было раскрыто - корабль или мина.
     *
     * @return тип цели (SHIP или MINE)
     */
    public TargetType getType() {
        return type;
    }

    /**
     * Проверяет, использована ли уже информация об этой цели.
     * Использованная цель не должна снова учитываться в игровой логике.
     *
     * @return true если цель использована, false в противном случае
     */
    public boolean isUsed() {
        return used;
    }

    /**
     * Помечает цель как использованную.
     * После вызова этого метода цель считается обработанной
     * и не должна использоваться повторно.
     */
    public void markAsUsed() {
        this.used = true;
    }

    /**
     * Перечисление типов целей, которые могут быть раскрыты в игре.
     * Определяет, какую именно информацию получил игрок при срабатывании
     * специальных событий (мин или тральщиков).
     */
    public enum TargetType {
        /**
         * Выданная клетка корабля.
         * Игрок получает информацию о точном местоположении клетки корабля противника.
         */
        SHIP,

        /**
         * Выданная клетка мины.
         * Игрок получает информацию о точном местоположении мины противника.
         */
        MINE
    }
}