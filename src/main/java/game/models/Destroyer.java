package game.models;

/**
 * Класс, представляющий эсминец в игре "Морской бой".
 * Эсминец является двухпалубным кораблем, занимающим 2 клетки на игровом поле.
 *
 * Наследуется от абстрактного класса Ship и наследует его базовую функциональность.
 * Эсминцы являются самыми маленькими обычными кораблями в игре (не считая подлодок).
 */
public class Destroyer extends Ship {

    /**
     * Создает новый экземпляр эсминца.
     * Устанавливает название корабля "Destroyer" и размер 2 клетки.
     *
     * Конструктор не принимает параметров, так как характеристики эсминца
     * фиксированы и не могут быть изменены. Эсминец всегда занимает две
     * смежные клетки на игровом поле.
     */
    public Destroyer() {
        super("Destroyer", 2);
    }
}