package game.models;

/**
 * Класс, представляющий подводную лодку в игре "Морской бой".
 * Подлодка является особым типом корабля с уникальными свойствами.
 * В отличие от обычных кораблей, подлодка имеет возможность
 * "ответного выстрела" при потоплении.
 *
 * Наследуется от абстрактного класса Ship и наследует его базовую функциональность.
 * Подлодка всегда занимает одну клетку на игровом поле.
 */
public class Submarine extends Ship {
    /**
     * Флаг, указывающий может ли подлодка совершить ответный выстрел.
     * Подлодка может ответить выстрелом только один раз - при своем потоплении.
     */
    private boolean canFireBack;

    /**
     * Создает новую подводную лодку.
     * Устанавливает название "Submarine", размер 1 клетка и
     * инициализирует возможность ответного выстрела.
     *
     * Подлодка создается с флагом canFireBack = true, что означает
     * возможность совершить ответный выстрел при потоплении.
     */
    public Submarine() {
        super("Submarine", 1);
        this.canFireBack = true;
    }

    /**
     * Обрабатывает попадание в подводную лодку.
     * При потоплении подлодки, если она еще может стрелять,
     * совершается ответный выстрел по противнику.
     *
     * @return true если подлодка потоплена, false если повреждена, но еще держится
     */
    @Override
    public boolean hit() {
        boolean sunk = super.hit();
        if (sunk && canFireBack) {
            canFireBack = false;
            return true;
        }
        return sunk;
    }

    /**
     * Проверяет, может ли подлодка совершить ответный выстрел.
     * Подлодка может ответить выстрелом только один раз - при своем потоплении.
     *
     * @return true если подлодка может совершить ответный выстрел,
     *         false если ответный выстрел уже был совершен или невозможен
     */
    public boolean canFireBack() {
        return canFireBack;
    }
}