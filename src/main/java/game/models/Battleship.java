package game.models;

/**
 * Класс, представляющий броненосец (линкор) в игре "Морской бой".
 * Броненосец является самым большим кораблем в игре, занимающим 4 клетки.
 *
 * Наследуется от абстрактного класса Ship и наследует его базовую функциональность.
 * Имеет фиксированный размер и не требует дополнительной настройки.
 */
public class Battleship extends Ship {

    /**
     * Создает новый экземпляр броненосца.
     * Устанавливает название корабля "Battleship" и размер 4 клетки.
     *
     * Конструктор не принимает параметров, так как характеристики броненосца
     * фиксированы и не могут быть изменены.
     */
    public Battleship() {
        super("Battleship", 4);
    }
}